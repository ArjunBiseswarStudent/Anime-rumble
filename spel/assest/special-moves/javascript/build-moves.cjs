// Rebuild browser data after editing moves-source.txt: node spel/assest/special-moves/javascript/build-moves.cjs
const fs = require('node:fs');
const path = require('node:path');
// Ordered exactly like the supplied document. IDs are the same as the game's roster.
const profiles = {
    naruto: ['dash', 'explosive'], sasuke: ['dash', 'zone'], sakura: ['ground', 'heal'],
    itachi: ['projectile', 'stun'], kakashi: ['dash', 'delayed'], jiraiya: ['guard', 'stream'],
    gaara: ['stun', 'delayed'], shikamaru: ['stun', 'zone'], kiba: ['dash', 'combo'],
    luffy: ['reach', 'heavy'], zoro: ['dash', 'spin'], sanji: ['melee', 'combo'],
    usopp: ['explosive', 'summon'], chopper: ['combo', 'transform'], nami: ['lightning', 'guided'],
    robin: ['stun', 'transform'], brook: ['melee', 'freeze'], goku: ['beam', 'bomb'],
    vegeta: ['beam', 'beam'], gohan: ['beam', 'beam'], piccolo: ['beam', 'orbit'],
    trunks: ['projectile', 'sword'], hit: ['teleport', 'stun'], frieza: ['beam', 'bomb'],
    beerus: ['heavy', 'bomb'], jiren: ['explosive', 'combo'], gojo: ['pull', 'projectile'],
    sukuna: ['slash', 'zone'], yuji: ['double', 'heavy'], jinwoo: ['teleport', 'summon'],
    cha: ['combo', 'sword'], beru: ['leap', 'combo'], deku: ['projectile', 'ground'],
    bakugo: ['beam', 'slam'], todoroki: ['ice', 'ground'], asta: ['leap', 'sword'],
    yuno: ['volley', 'sword'], noelle: ['stream', 'transform'], tanjiro: ['spin', 'combo'],
    nezuko: ['zone', 'transform'], zenitsu: ['dash', 'combo'], natsu: ['stream', 'heavy'],
    erza: ['volley', 'transform'], gray: ['volley', 'projectile'], sonic: ['dash', 'transform'],
    shadow: ['volley', 'ground'], knuckles: ['dash', 'heavy'], mario: ['bounce', 'uppercut'],
    bowser: ['stream', 'slam'], dk: ['heavy', 'ground'], cloud: ['slash', 'combo'],
    sephiroth: ['orbit', 'combo'], tifa: ['combo', 'heavy'], denji: ['dash', 'combo'],
    power: ['heavy', 'rain'], aki: ['summon', 'delayed']
};
const source = fs.readFileSync(path.join(__dirname, '../moves-source.txt'), 'utf8');
const records = [];
let name = '', current;
for (const raw of source.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line) continue;
    if (/^[QE] - /.test(line)) {
        const split = line.lastIndexOf(': ');
        if (split < 0) throw new Error('Invalid move line: ' + line);
        if (line[0] === 'Q') { current = { character: name, moves: [] }; records.push(current); }
        current.moves.push({ name: line.slice(4, split), desc: line.slice(split + 2) });
    } else name = line;
}
const entries = Object.entries(profiles);
if (records.length !== entries.length || records.some(record => record.moves.length !== 2)) throw new Error('Expected 56 characters with two moves each.');
const registry = {};
records.forEach((record, index) => {
    const [id, kinds] = entries[index];
    registry[id] = record.moves.map((move, slot) => {
        const kind = kinds[slot];
        return {
            ...move, kind, damage: ['transform', 'heal', 'guard'].includes(kind) ? 0 : slot ? 30 : 14,
            cooldown: slot ? 16 : 5, windup: slot ? 0.65 : 0.18,
            duration: ['transform', 'heal', 'guard'].includes(kind) ? 6 : ['zone', 'stream', 'summon'].includes(kind) ? 2.4 : slot ? 1.8 : 0.65,
            range: slot ? 270 : 155, character: record.character
        };
    });
});
fs.writeFileSync(path.join(__dirname, 'moves.json'), JSON.stringify(registry, null, 2) + '\n');
fs.writeFileSync(path.join(__dirname, 'moves-data.js'), '// Generated by build-moves.cjs from moves-source.txt.\nwindow.SpecialMoveData = ' + JSON.stringify(registry, null, 2) + ';\n');
console.log(`Built ${records.length * 2} moves for ${records.length} characters.`);
